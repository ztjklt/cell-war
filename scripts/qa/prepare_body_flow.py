"""Offline visibility analysis only. Never changes reference pixels or gameplay routes.

Emit arc intervals on existing display curves. Pigment masks, foreground organ
polygons and subpixel clearance bound the runtime strokes. No image scan at runtime.
Run: PYTHONPATH=/tmp/reference-map-tools python3 scripts/qa/prepare_body_flow.py
"""
from pathlib import Path
import hashlib
import cv2
import numpy as np
from PIL import Image
from lupa.lua54 import LuaRuntime

ROOT = Path(__file__).resolve().parents[2]
source = ROOT/'assets/image/anatomy-reference/reference.png'
rgb = np.asarray(Image.open(source).convert('RGB')).astype(np.int16)
lua = LuaRuntime(unpack_returned_tuples=True)
lua.execute("package.path="+repr(str(ROOT/'scripts/?.lua'))+"..';'..package.path")
net = lua.eval("require('war.Vessels').forDisplay({anatomyVersion=4})")
M = lua.eval("require('war.ReferenceMap')")
C = lua.eval("require('war.VesselCurves')")
r,g,b = rgb[:,:,0],rgb[:,:,1],rgb[:,:,2]
# No generic blue selection: only curves already authored as veins are eligible.
blue = ((b-r>12)&(g-r>6)&(b>100)).astype(np.uint8)
red = ((r-g>72)&(r-b>55)&(g<130)&(b<140)&(r>165)).astype(np.uint8)
foreground = np.zeros(red.shape,np.uint8)
for organ in M['organs'].values():
    points = np.array([[p[1]/2,(p[2]-512)/2] for p in organ['points'].values()],np.int32)
    cv2.fillPoly(foreground,[points],1)
# Coarse polygons only exclude effect eligibility; they never create image cutouts.
red[foreground>0] = 0
blue[foreground>0] = 0
# The real trachea and cartilage remain fixed even where source colors are mixed.
red[155:330,496:522] = 0
blue[155:330,496:522] = 0
clearance = {k:cv2.distanceTransform(v,cv2.DIST_L2,5) for k,v in [('artery',red),('vein',blue)]}
reverse = {'heart.v → cava_upper','cava_upper → cava_mid','cava_mid → cava_abd',
           'cava_abd → iliac.v','iliac.v → hip_r.v','iliac.v → hip_l.v',
           'cava_mid → gut_right.v','gut_right.v → iliac.v'}
for side in ('r','l'):
    reverse.update({f'armfork_{side}.v → elbow_{side}.v',f'elbow_{side}.v → wrist_{side}.v',
                    f'thighfork_{side}.v → knee_{side}.v',f'calffork_{side}.v → {side}.calf_tip.v'})

rows=[]
for eid,e in net['edges'].items():
    kind=e['system']; name=e['name']; spans=[]
    sign=-1 if name in reverse else 1
    if kind not in clearance or e['hidden']:
        rows.append((eid,name,sign,spans)); continue
    # Half a source pixel per sample. Source pigment determines display system:
    # old authored arterial/venous polylines sometimes lie on the opposite pigment.
    # Direction follows each route's proximal/distal semantics, inverted for those
    # spans only. The simulation edge system and route geometry are never changed.
    count=int(np.ceil(e['length']))
    samples=[]
    for i in range(count+1):
        d=min(i,e['length']); x,y,_,_=C['at'](e,d)
        sx,sy=x/2,(y-512)/2;ix,iy=int(round(sx)),int(round(sy))
        width=0; display=''
        if 0<=iy<rgb.shape[0] and 0<=ix<rgb.shape[1]:
            for pigment in ('vein','artery'):
                depth=float(clearance[pigment][iy,ix])
                # Deep wide red areas are muscle, not a short visible vessel.
                if pigment=='artery' and depth>5:continue
                radius=max(0,depth-.95)*2
                width=np.floor(min(e['width']*.48,radius*1.3)*2)/2
                if width>=.5:display=pigment;break
        samples.append((d,display,width if display else 0))
    start=0
    while start<len(samples):
        end=start+1
        while end<len(samples) and samples[end][1]==samples[start][1]:end+=1
        # At least four source pixels before a color change counts as a route.
        if samples[start][1] and end-start>=8:
            k=start
            while k<end:
                stop=min(k+49,end)
                if stop-k>=3:
                    ds=samples[k][0]+.6;de=samples[stop-1][0]-.6
                    width=min(q[2] for q in samples[k:stop])
                    display=samples[k][1]
                    spans.append([round(ds,3),round(de,3),float(width),
                                  1 if display=='artery' else -1,
                                  sign if display==kind else -sign])
                k=stop
        start=end
    rows.append((eid,name,sign,spans))

def fmt(v):return str(int(v)) if int(v)==v else str(v)
out=['-- Generated by scripts/qa/prepare_body_flow.py; source coordinates and graph are unchanged.',
     '-- Span {arcStart, arcEnd, safeStrokeWidth, pigmentSign, flowSign}; + pigment = red, - = blue.',
     'return {version=4,sourceSha256="'+hashlib.sha256(source.read_bytes()).hexdigest()+'",edges={']
for eid,name,sign,spans in rows:
    out.append(f' [{eid}]={{name="{name}",flowSign={sign},spans={{'+','.join('{'+','.join(fmt(v) for v in span)+'}' for span in spans)+'}},')
out.append('}}\n')
(ROOT/'scripts/war/BodyLifeFlowData.lua').write_text('\n'.join(out))
print({'edges':len(rows),'visibleEdges':sum(bool(r[3]) for r in rows),'spans':sum(len(r[3]) for r in rows),'reversed':sum(r[2]<0 for r in rows)})
