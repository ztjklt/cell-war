"""Package registered channel tiles and exact crossing depth for the game.

Tight image crops only discard transparent margins. Their source coordinate
boxes retain fractional pixel registration; graph/collision data is untouched.
"""
from pathlib import Path
import hashlib
import json
import sys
import xml.etree.ElementTree as ET
from PIL import Image
from shapely.geometry import Point
from shapely.ops import unary_union

sys.path.insert(0,str(Path(__file__).parent))
from build_fullbody_vascular_material import svg_geometry

ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'assets/image/anatomy-reference/vascular-study/standalone-vessels-20261015'
SOURCE=BASE/'channels-v3'
OUT=ROOT/'docs/standalone-vessels-20261015/runtime-integration'


def lua(v):
    if v is None:return 'nil'
    if isinstance(v,bool):return 'true'if v else'false'
    if isinstance(v,(int,float)):return repr(v)
    if isinstance(v,str):return json.dumps(v,ensure_ascii=False)
    if isinstance(v,list):return '{'+','.join(lua(q)for q in v)+'}'
    return '{'+','.join('['+lua(k)+']='+lua(q)for k,q in v.items())+'}'


def rings(g):
    if g.is_empty:return []
    if g.geom_type=='Polygon':return [dict(outer=[list(p)for p in g.exterior.coords],holes=[[list(p)for p in ring.coords]for ring in g.interiors])]
    return [p for part in getattr(g,'geoms',[])for p in rings(part)]


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    manifest=json.loads((SOURCE/'manifest.json').read_text())
    geometry=json.loads((ROOT/'docs/standalone-vessels-20261015/manifest.json').read_text())
    paths=ET.parse(BASE/'vessels-geometry.svg').getroot()
    shapes={int(p.attrib['id'].split('-')[-1]):svg_geometry(p.attrib['d'])for p in paths}
    tiles=[];bytes_per_level={level:0 for level in manifest['levels']}
    for tile in manifest['tiles']:
        versions={}
        for level in manifest['levels']:
            im=Image.open(SOURCE/f'l{level}'/tile['name']).convert('RGBA')
            b=im.getchannel('A').getbbox();assert b
            b=[max(0,b[0]-2),max(0,b[1]-2),min(im.width,b[2]+2),min(im.height,b[3]+2)]
            cropped=im.crop(tuple(b));target=SOURCE/'runtime'/f'l{level}'/tile['name'];target.parent.mkdir(parents=True,exist_ok=True);cropped.save(target)
            width,height=cropped.size;bytes_per_level[level]+=width*height*4
            versions[level]=dict(id=f'channel-{level}-{tile["x"]}-{tile["y"]}',resource=str(target.relative_to(ROOT/'assets')),pixelSize=[width,height],sourceBox=[tile['x']+b[0]/level,tile['y']+b[1]/level,tile['x']+b[2]/level,tile['y']+b[3]/level])
        tiles.append(dict(id=tile['name'],sourceBox=[tile['x'],tile['y'],tile['x']+tile['w'],tile['y']+tile['h']],levels=versions))
    edges=geometry['edges'];crossings={};count=0
    for lower in edges:
        owned=[]
        for upper in edges:
            if upper['layer']<=lower['layer']:continue
            overlap=shapes[lower['lane']].intersection(shapes[upper['lane']])
            if overlap.is_empty:continue
            shared={lower['a'],lower['b']}&{upper['a'],upper['b']}
            for node in shared:
                p=lower['samples'][0 if lower['a']==node else -1]
                overlap=overlap.difference(Point(p).buffer(max(lower['widthSource'],upper['widthSource'])*2))
            if overlap.area>1e-6:owned.append(overlap)
        occluded=unary_union(owned)
        if not occluded.is_empty:
            crossings[lower['lane']]=dict(sourceBox=list(occluded.bounds),rings=rings(occluded));count+=1
    record=dict(version=1,levels=manifest['levels'],tiles=tiles,bloodLanes={e['lane']:True for e in edges},crossings=crossings,
                baseDecodedBytes=bytes_per_level[4],maxHighDecodedBytes=72*1024*1024,sourceSize=[1024,1536],
                geometrySha256=manifest['geometrySourceSha256'],authoringManifestSha256=hashlib.sha256((SOURCE/'manifest.json').read_bytes()).hexdigest())
    (ROOT/'scripts/war/VesselChannelsData.lua').write_text('-- Registered channel art; no navigation changes. Generated by prepare_vessel_channels_runtime.py.\nreturn '+lua(record)+'\n')
    (OUT/'resources.json').write_text(json.dumps(dict(tileCount=len(tiles),bytesPerLevel=bytes_per_level,crossingLanes=count,geometrySha256=record['geometrySha256'],lowLevelBytes=record['baseDecodedBytes'],maxHighDecodedBytes=record['maxHighDecodedBytes']),ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(dict(tiles=len(tiles),bytesPerLevel=bytes_per_level,crossingLanes=count)),flush=True)


if __name__=='__main__':main()
