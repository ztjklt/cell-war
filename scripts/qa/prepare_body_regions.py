"""Analyze original pigment into interior-only effect paths; never rewrites the image.
Authored polygons initialize the ROI. Pixel colour, overlaps, foreground and an
inset safety distance determine the final effect mask (not the organ silhouette).
"""
from pathlib import Path
import numpy as np, cv2
from PIL import Image
from lupa.lua54 import LuaRuntime
l=LuaRuntime(unpack_returned_tuples=True)
l.execute("package.path='scripts/?.lua;'..package.path;M=require('war.ReferenceMap')")
m=l.globals().M
fixed=l.eval("require('war.BodyLifeMasks')")[0]
rgb=np.asarray(Image.open('assets/image/anatomy-reference/reference.png').convert('RGB')).astype(np.int16)
r,g,b=rgb[:,:,0],rgb[:,:,1],rgb[:,:,2]
blue=(b-r>0)&(g-r>0)
bone=(r>170)&(g>165)&((r-g)<52)&((g-b)>12)
dark=(r<125)|(r+g+b<300)
forbidden=cv2.dilate((blue|bone|dark).astype('uint8'),np.ones((3,3),np.uint8))>0
# Generated lung inpaint can shift a pale inner rim by a few source pixels.
# Protect bright markings from both images plus the maximum source displacement;
# this analyzes pixels into geometry, and never edits either bitmap.
lung_rim=(r>235)&(g>190)&(b>150)
inpaint=Path('assets/image/anatomy-reference/body-life/lung-tissue-inpaint.png')
if inpaint.exists():
 generated=np.asarray(Image.open(inpaint).convert('RGB')).astype(np.int16)
 assert generated.shape==rgb.shape,'Lung atlas must retain original canvas coordinates'
 gr,gg,gb=generated[:,:,0],generated[:,:,1],generated[:,:,2]
 lung_rim|=(gr>235)&(gg>190)&(gb>150)
lung_rim=cv2.dilate(lung_rim.astype('uint8'),np.ones((11,11),np.uint8))>0
organs=list(m.organs.values());raw={}
for o in organs:
 p=np.array([[round(float(q[1])/2),round((float(q[2])-512)/2)] for q in o.points.values()],np.int32)
 a=np.zeros((1536,1024),np.uint8);cv2.fillPoly(a,[p],255);raw[o.id]=a
def paths_of(a):
 cs,hierarchy=cv2.findContours(a,cv2.RETR_CCOMP,cv2.CHAIN_APPROX_SIMPLE)
 if hierarchy is None:return []
 return [{'points':cv2.approxPolyDP(c,.6,True).reshape(-1,2).tolist(),'hole':bool(hierarchy[0][i][3]>=0)} for i,c in enumerate(cs) if cv2.contourArea(c)>=2]
result=[];shade_result=[]
for idx,o in enumerate(organs):
 a=raw[o.id].copy()
 for front in organs[idx+1:]:a[raw[front.id]>0]=0
 a=cv2.erode(a,np.ones((9,9),np.uint8))
 if o.id in ('lung_r','lung_l'):
  shade=a.copy()
  # Lighting has no displacement: the mesh's 5px safety margin would create
  # conspicuous unlit rings around every bronchial branch. Keep only exact
  # source foreground pigment out of the lighting mask.
  shade[blue|bone|dark]=0
  shade_result.append((o.id,paths_of(shade)))
 if o.id=='heart':
  # Yellow coronary branches are painted myocardium details, not ivory bone.
  # They must contract with the heart; the great-vessel masks below stay fixed.
  a[cv2.dilate((blue|dark).astype('uint8'),np.ones((3,3),np.uint8))>0]=0
 else:a[forbidden]=0
 if o.id in ('lung_r','lung_l'):a[lung_rim]=0
 if fixed[o.id] is not None:
  protected=np.zeros_like(a)
  for path in fixed[o.id].values():
   cv2.fillPoly(protected,[np.array([list(v.values()) for v in path.values()],np.int32)],255)
  # Guarantee the simplified contour cannot re-enter a fixed foreground pixel.
  protected=cv2.dilate(protected,np.ones((5,5),np.uint8))
  a[protected>0]=0
 # Heart great vessel attachment remains fully fixed.
 if o.id=='heart':a[:390,:]=0
 a=cv2.morphologyEx(a,cv2.MORPH_OPEN,np.ones((3,3),np.uint8))
 paths=paths_of(a)
 result.append((o.id,paths))
# Muscle interiors are selected by original pigment within separate source ROIs.
for name,(x,y,w,h) in {'arm_r':(296,417,45,100),'arm_l':(677,417,45,100),'forearm_r':(244,585,27,86),'forearm_l':(748,585,28,86),'thigh_r':(368,802,51,104),'thigh_l':(601,802,52,104),'calf_r':(369,1059,26,108),'calf_l':(624,1059,24,108)}.items():
 a=np.zeros((1536,1024),np.uint8);a[y:y+h,x:x+w]=255
 a[(r-g<48)|(b<65)|forbidden]=0
 a=cv2.erode(a,np.ones((5,5),np.uint8))
 paths=paths_of(a)
 result.append((name,paths))
def lua(v):
 if isinstance(v,list):return '{'+','.join(lua(x) for x in v)+'}'
 if isinstance(v,dict):return '{'+','.join(k+'='+lua(x) for k,x in v.items())+'}'
 if isinstance(v,bool):return str(v).lower()
 return str(v)
text='-- Source-pigment interior masks, generated by prepare_body_regions.py.\nreturn {\n'+',\n'.join(k+'='+lua(paths) for k,paths in result)+'\n}\n'
Path('scripts/war/BodyLifeRegions.lua').write_text(text)
Path('scripts/war/BodyLifeLightingRegions.lua').write_text('-- Source-pigment lighting masks; no deformation safety padding.\nreturn {\n'+',\n'.join(k+'='+lua(paths) for k,paths in shade_result)+'\n}\n')
print({k:sum(len(p["points"]) for p in paths) for k,paths in result})
