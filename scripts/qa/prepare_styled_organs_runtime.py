"""Package the approved, silhouette-clipped organ vectors for game zoom levels.

Rasterization and tile cropping only; no generative edits or geometry changes.
"""
from pathlib import Path
import hashlib, io, json, sys, xml.etree.ElementTree as ET
import cairosvg
from PIL import Image
sys.path.insert(0, str(Path(__file__).parent))
from prepare_vessel_channels_runtime import lua

ROOT=Path(__file__).resolve().parents[2]
ASSET=ROOT/'assets/image/anatomy-reference/organ-style-20261015'
DOC=ROOT/'docs/organ-style-20261015/runtime-integration'
LEVELS=[4,8,16,32]

def main():
    DOC.mkdir(parents=True,exist_ok=True)
    manifest=json.loads((ASSET/'manifest.json').read_text())
    tiles=[];byte_counts={n:0 for n in LEVELS}
    for organ in manifest['organs']:
        oid=organ['id']; b=organ['sourceBox'];x,y,right,bottom=b
        tree=ET.parse(ASSET/organ['registeredVector']).getroot()
        body=''.join(ET.tostring(q,encoding='unicode')for q in tree)
        organ_tiles=[]
        for ty in range(y,bottom,64):
            for tx in range(x,right,64):
                organ_tiles.append(dict(id=f'{oid}-{tx}-{ty}',organId=oid,sourceBox=[tx,ty,min(tx+64,right),min(ty+64,bottom)],levels={}))
        for level in LEVELS:
            w,h=(right-x)*level,(bottom-y)*level
            svg=f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="{x} {y} {right-x} {bottom-y}">{body}</svg>'
            image=Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.encode()))).convert('RGBA')
            for tile in organ_tiles:
                tb=tile['sourceBox'];crop=image.crop(((tb[0]-x)*level,(tb[1]-y)*level,(tb[2]-x)*level,(tb[3]-y)*level))
                if not crop.getchannel('A').getbbox():continue
                target=ASSET/'runtime'/f'l{level}'/(tile['id']+'.png');target.parent.mkdir(parents=True,exist_ok=True);crop.save(target)
                tile['levels'][level]=dict(id=f'organ-{level}-{tile["id"]}',resource=str(target.relative_to(ROOT/'assets')),sourceBox=tb,pixelSize=list(crop.size))
                byte_counts[level]+=crop.width*crop.height*4
        for tile in organ_tiles:
            if tile['levels']:
                assert len(tile['levels'])==len(LEVELS)
                tiles.append(tile)
        print(oid,len([t for t in organ_tiles if t['levels']]),flush=True)
    record=dict(version=1,levels=LEVELS,tiles=tiles,baseDecodedBytes=byte_counts[4],maxHighDecodedBytes=72*1024*1024,
                sourceSize=[1024,1536],authoringManifestSha256=hashlib.sha256((ASSET/'manifest.json').read_bytes()).hexdigest(),organCount=12)
    (ROOT/'scripts/war/StyledOrgansData.lua').write_text('-- Approved organ artwork, immutable source registration. Generated by prepare_styled_organs_runtime.py.\nreturn '+lua(record)+'\n')
    (DOC/'resources.json').write_text(json.dumps(dict(tileCount=len(tiles),bytesPerLevel=byte_counts,sourceSize=record['sourceSize'],organs=manifest['organs']),ensure_ascii=False,indent=2)+'\n')
    print('COMPLETE',len(tiles),byte_counts,flush=True)

if __name__=='__main__':main()
